#!/usr/bin/env python3
"""Inventory repository Markdown and enforce reviewed document authority.

Git supplies tracked + non-ignored untracked paths. No dependencies or secrets
are crawled. Unknown documents remain needs-review; no age-based inference.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import quote, unquote, urlsplit
import os

ROOT = Path(__file__).resolve().parents[1]
REPORT = 'docs/code-health/document-classification.md'
STATUSES = {'current-reference', 'active-plan', 'historical', 'superseded', 'needs-review'}


def inventory(root):
    result = subprocess.run(
        ['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', '*.md'],
        cwd=root, check=True, capture_output=True,
    )
    return sorted(set(result.stdout.decode().strip('\0').split('\0')) | {REPORT})


def classify(paths, policy):
    rows = {}
    for name in paths:
        rows[name] = policy['documents'].get(name, {
            'status': 'needs-review',
            'evidence': 'Not substantively reviewed against implementation. Do not use as current authority without checking the relevant code and tests.',
        })
    return rows


def validate(root, rows, policy):
    errors = []
    for name in policy['documents']:
        if name not in rows:
            errors.append(f'{name}: classification points to a missing document')
    for name, item in rows.items():
        status = item['status']
        if status not in STATUSES:
            errors.append(f'{name}: unknown status {status}')
        if not item.get('evidence'):
            errors.append(f'{name}: missing evidence/review scope')
        if status == 'superseded':
            replacement = item.get('replacement')
            if not replacement or not (root / replacement).exists():
                errors.append(f'{name}: missing replacement target')
            if 'Superseded — not implementation guidance' not in (root / name).read_text()[:1200]:
                errors.append(f'{name}: missing visible supersession notice')
        if status != 'current-reference' or name == REPORT:
            continue
        text = re.sub(r'```.*?```', '', (root / name).read_text(), flags=re.S)
        for line in text.splitlines():
            for target in re.findall(r'\[[^\]\n]*\]\(([^\s)]+)\)', line):
                url = urlsplit(target)
                if url.scheme or url.netloc or not url.path:
                    continue
                resolved = (root / name).parent.joinpath(unquote(url.path)).resolve()
                if not resolved.is_relative_to(root.resolve()):
                    continue
                linked = rows.get(resolved.relative_to(root.resolve()).as_posix(), {})
                if linked.get('status') in {'superseded', 'historical'} and not re.search(r'\b(?:Historical|History|Superseded):', line):
                    errors.append(f'{name}: label history link explicitly: {target}')
    return errors


def render(rows, policy):
    counts = Counter(item['status'] for item in rows.values())
    lines = [
        '# Document classification', '',
        'Up: [Docs index](../INDEX.md) · Status: current audit inventory', '',
        '<!-- Generated by scripts/audit-docs.py --write; edit scripts/doc-classification.json, not this table. -->', '',
        policy['basis'], '',
        '**This is an initial authority triage, not a completed semantic audit of every file.** Unknown files remain needs-review. Historical describes a document, not feature removal. Superseded means unsafe as current implementation guidance; useful decisions may remain.', '',
        '## Coverage', '',
        f'{len(rows)} Markdown files (tracked plus non-ignored local additions).', '',
    ]
    lines += [f'- **{status}:** {counts[status]}' for status in sorted(STATUSES)]
    lines += [
        '', 'No claim is made about production deployments. Code comparison is scoped in each evidence cell. Unimplemented proposals are not automatically abandoned.', '',
        '## How to use', '',
        '- Check this inventory before treating an older document as authority.',
        '- **Current reference:** reviewed for its stated scope, not necessarily every feature claim.',
        '- **Active plan:** approved future work; not a statement of implemented behaviour.',
        '- **Historical / superseded:** consult for rationale only; do not restore old behaviour from these documents.',
        '- **Needs review:** inspect owning code/tests before planning; resolve ambiguous product intent with Tom.', '',
        'Run `python3 scripts/audit-docs.py` to check policy and report freshness. Use `--write` to regenerate after adding evidence to the JSON registry. The default never promotes unreviewed files.', '',
        '## Per-file classification', '',
        '| Document | Classification | Evidence and review scope |',
        '|---|---|---|',
    ]
    for name, item in rows.items():
        target = quote(os.path.relpath(name, Path(REPORT).parent), safe='/.-_')
        evidence = item['evidence'].replace('|', '\\|').replace('\n', ' ')
        lines.append(f'| [{name}]({target}) | {item["status"]} | {evidence} |')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Regenerate audit report only')
    args = parser.parse_args()
    policy = json.loads((ROOT / 'scripts/doc-classification.json').read_text())
    rows = classify(inventory(ROOT), policy)
    errors = validate(ROOT, rows, policy)
    report = render(rows, policy)
    target = ROOT / REPORT
    if args.write:
        target.write_text(report)
    elif not target.exists() or target.read_text() != report:
        errors.append('Classification inventory is stale; run scripts/audit-docs.py --write')
    for error in errors:
        print(error)
    counts = Counter(item['status'] for item in rows.values())
    print(f'{len(rows)} documents; {counts["needs-review"]} need review; {len(errors)} validation error(s).')
    return bool(errors)


if __name__ == '__main__':
    sys.exit(main())
